local function hvNow()
  if os and os.time then
    local ok, t = pcall(os.time)
    if ok and type(t) == "number" and t > 1.7e9 then
      return t
    end
  end
  if getTime then
    local ok, t = pcall(getTime)
    if ok and type(t) == "number" then
      if t > 1.7e12 then
        return math.floor(t / 1000)
      end
      if t > 1.7e9 then
        return t
      end
    end
  end
  return nil
end
