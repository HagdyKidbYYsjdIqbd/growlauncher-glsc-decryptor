               return false
            end
         end
      
         if isBlocked then
            isBlocked = false
            stopScript("Gagal drop karena terhalang block.")
            return false
         end
         
         if isFull then
            full = true
         else
            if config.separatedDrop then
               local dx, dy = parseXY(itemPos[id])
            
               dropPos[dx .. ":" .. dy] = true
               dropPos[(dx + 1) .. ":" .. dy] = true
            else
               dropPos[config.dx .. ":" .. config.dy] = true
               dropPos[(config.dx + 1) .. ":" .. config.dy] = true
            end   
            return type(dropCount) == "number" and cekInv(id) < before or cekInv(id) <= 0
         end
      end
      
      if full then
         isFull = false
         local x, y = parseXY(itemPos[id])
         local nx = config.separatedDrop and x or config.dx
         local ny = config.separatedDrop and y or config.dy
         local dx = config.dropMode == 0 and nx - 1 or nx
         local dy = config.dropMode == 0 and ny or ny - 1
         
         if not dx or not dy or dx < 0 then
            stopScript("Posisi drop invalid.")
            return false
         end
         
         if config.separatedDrop then
            local pos = dx..", "..dy
            itemPos[id] = pos
         else
            ev("dropPos", dx..", "..dy)
            cfgTime = 0
         end   
         
         if not Fp(dx, dy, true) then
            stopScript("Gagal findPath ke area drop")
            return false 
         end
      end
   end
   
   return false
end

