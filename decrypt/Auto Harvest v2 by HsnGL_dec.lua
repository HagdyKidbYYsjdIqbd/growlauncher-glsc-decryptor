   if not premiumCheck() then
      return
   end
      
   if not k then
      logs(r)
      stopScript(r)
      return
   end
      
   if config.key ~= keyPass and not premium then
      stopScript("Invalid Key\nDapatkan key di Discord Server.")
      return
   end
   
   if not targetID or targetID == 0 or targetID == 6 then
      stopScript("Target Invalid, berdiri di pohon atau provider\nyang akan di panen!")
      return
   end 
   
   if not targetWorlds or #targetWorlds < 1 then
      stopScript("Target World tidak boleh kosong!")
      return
   end   
   
   if (config.dropWorld == "N/A" or config.dropWorld == "")
      and config.dropWorldOption == 1 then
      stopScript("Save World tidak boleh kosong!")
      return
   end   
   
   if not validXY(gv(2, "dropPos")) and config.autoCollect then
      stopScript("Posisi drop tidak valid!")
      return 
   end
   
   if config.autoTakeFuel and (config.fuelWorld == "N/A"
      or config.fuelWorld == "") then
      stopScript("Fuel World tidak boleh kosong!")
      return 
   end
   
   if config.customWebhook and not w(config.customWebhookUrl):find("https://discord.com/api/webhooks/") then
      stopScript("Webhook URL invalid!")
      return
   end
   
   if config.delay < 180 then
      dialogBuilder("Low Delay Warning âš ï¸", "Kamu menggunakan delay yang singkat\njangan gunakan delay singkat jika kamu lag!\nDelay aman adalah 180.", "Understand")
   end
      
   webhookSent = false
   
   saveConfigs()
   editToggle("ModFly", true)
   editToggle("collectfilter_onlytake", true)
   editToggle("collectfilter_enable", true)
   editToggle("cheat_config_fastdrop_active", false)
   
   local savedPos = config.dx..", "..config.dy
   dropPos[config.dx .. ":" .. config.dy] = true
   dropPos[(config.dx + 1) .. ":" .. config.dy] = true
   
   local startY, endY, stepY
   local y
   
   if config.sweepBottom then
      startY, endY, stepY = 53, 0, -1
   else
      startY, endY, stepY = 0, 53, 1
   end
   y = startY
   
   if not Warp(targetWorlds[twIndex]) then
      stopScript("Gagal warp ke Target World.")
      return false
   end
   
   getTargetCount()
   
   while running and ((y <= endY and stepY == 1) 
      or (y >= endY and stepY == -1)) do
      
      local isRetryRow = true
      local attempt = 0
         
      while running and isRetryRow do
         isRetryRow = false
         attempt = attempt + 1
         if attempt > config.maxRetries then break end
            
         local startX, endX, stepX = getDir()
         if not startX then 
            stopScript("Gagal menyambung ulang.")
            return
         end
            
         local x = startX
            
         while running and isOnRow(x, endX, stepX) do
            local ok
            ok, x, _, isRetryRow = doHarvest(x, y, stepX, targetID, isRetryRow)
               
            if not ok then
               if not running then return end 
               stopScript("")
               return
            end
         end
      end
   
      y = y + stepY
   
      if (y > endY and stepY == 1) or (y < endY and stepY == -1) then
         twIndex = twIndex + 1
         
         if premium and running then
            if twIndex > #targetWorlds then
               sendWebhook(1)
               stopScript("Finished!\nNo more "..getItemInfoByID(targetID).name.." to harvest.")
               return
            end
         
            Notify("Move to next world...")
            
            if not Warp(targetWorlds[twIndex]) then
               stopScript("Gagal warp ke world selanjutnya")
               return
            end
            y = startY
            sendWebhook(2)
            globalWorldCount = globalWorldCount + 1
            getTargetCount()
            if config.dropWorldOption == 0 then
               ev("dropPos", savedPos)
            end   
            webhookSent = false
         else
            if not running then
               return
            end 
               
            sendWebhook(1)
            stopScript("Finished!\nNo more "..getItemInfoByID(targetID).name.." to harvest.")
            return
         end
      end   
   end
   return false
end

