local function parseXY(str)
   local a, b = w(str):match("(-?%d+)%.?%d*%s*,%s*(-?%d+)")
   return tonumber(a), tonumber(b)
end

local function validXY(str)
   local x, y = parseXY(str)
   return x ~= nil and y ~= nil and x >= 0 and y >= 0
end

