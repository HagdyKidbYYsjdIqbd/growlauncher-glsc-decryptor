         stopScript("Gagal untuk menyambung ulang")
         return false
      end
   end
      
   if cekInv(id) <= 0 then return true end
   
   for _ = 1, 10 do
      local config = getVar(true)
      local full = false
      
      isDrop, isFull, isBlocked = false, false, false
      timeout = 0
      
      growtopia.dropItem(id)
      repeat
         Sleep(10)
         timeout = timeout + 1
      until isDrop or isFull or isBlocked or timeout >= ACTION_TIMEOUT * 10
         or Disconnected() or not running
      
      if timeout >= ACTION_TIMEOUT * 10 or not running then return false end
      if Disconnected() then
