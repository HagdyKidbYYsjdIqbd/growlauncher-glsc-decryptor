local function advSleep(baseDelay, safeDelay)
   local maxDelay = 1000
   local ping = getPing()
   local pingLow, pingHigh = 380, ping >= 500 and ping or 500
    
   if ping < pingLow then
      Sleep(baseDelay)
      return
   end

   local t = math.min((ping - pingLow) / (pingHigh - pingLow), 1)
   local tt = math.floor(baseDelay + (maxDelay - baseDelay) * t)
   local offset = safeDelay and math.floor(tt * 0.1)
      or math.floor(baseDelay * 0.1)
   
   local finalDelay = safeDelay and math.random(tt - offset, tt + offset)
      or math.random(baseDelay - offset, baseDelay + offset)
   
   Sleep(finalDelay)   
end

