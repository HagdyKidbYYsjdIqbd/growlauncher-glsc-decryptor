local function doHarvest(x, y, stepX, targetID, isRetryRow)
   local config = getVar()
   local matchTile = {}
   local isRetry = false
   
   if Disconnected() then
      if not Reconnect(targetWorlds[twIndex]) then
         stopScript("Gagal untuk menyambung ulang.")
         return false
      end   
   end
         
   if not Warp(targetWorlds[twIndex]) then
      stopScript("Gagal warp ke Target World.")
      return false
   end
   
   for i = 0, 2 do
      local cx = x + i * stepX
      
      if cx >= 0 and cx <= 99 then
         local tile = getTile(cx, y)
         
         if tile and tile.fg == targetID and tile.readyharvest then
            table.insert(matchTile, cx)
         end
      end
   end  
            
   if #matchTile == 0 then
      return true, x + 3 * stepX, false, isRetryRow
   end
   
   if config.autoTakeFuel and cekInv(FUEL_PACK) < 3 then
      if not takeFuels() then
         stopScript("Tidak bisa menemukan Fuel Pack")
         return false
      end
      
      if not Warp(targetWorlds[twIndex]) then
         stopScript("Gagal warp ke Target World.")
         return false
      end
   end
   -- urutan posisi FindPath: median dulu, lalu sisanya sebagai cadangan
   local medianIndex = math.ceil(#matchTile / 2)
   local cekOrder = {medianIndex}
            
   for i = 1, #matchTile do
      if i ~= medianIndex then
         table.insert(cekOrder, i)
      end  
   end
   
   -- coba satu per satu sampai ada yang berhasil
   local isReached = false
            
   for _, idx in ipairs(cekOrder) do
      if not running then stopScript("") return false end
      
      if Disconnected() then
         if not Reconnect(targetWorlds[twIndex]) then
            stopScript("Gagal untuk menyambung ulang.")
            return false
         end   
      end
      
      if Fp(matchTile[idx], y) then
         isReached = true
         break
      else
         local px, py = getPos(); if not px then
            if not Reconnect(targetWorlds[twIndex]) then
               stopScript("Gagal untuk menyambung ulang")
               return false
            end
            px, py = getPos()
         end
         
         local tile = getTile(px, py)
         
         if tile and tile.fg == 6 then
            if not Warp(targetWorlds[twIndex], true) then
               stopScript("Gagal untuk warp ke Target World")
               return false
            end
            
            if Fp(matchTile[idx], y) then
               isReached = true
               break
            end   
         end
      end   
   end
               
   if isReached then
      isRetry = true
      isRetryRow = true
      
      for _, dx in ipairs(cekOrder) do
         local harvested = false
         local attempt = 0
         
         if not running then return false end 
         if Disconnected() then
            if not Reconnect(targetWorlds[twIndex]) then               
               stopScript("Gagal Menyambung ulang")
               return false
            end
         end
                  
         if not config.antiMiss then
            if harvest(matchTile[dx], y) and not Disconnected() then
               advSleep(config.delay, config.safeDelay)
            end   
         else
            while not harvested and attempt <= 10 do
               local timeout = 0
               
               if harvest(matchTile[dx], y) and not Disconnected() then
                  repeat
                     Sleep(10)
                     timeout = timeout + 10
                  until getTile(matchTile[dx], y) and not getTile(matchTile[dx], y).readyharvest or Disconnected() or not running or timeout >= 1000
                  
                  if not running then return false end
                  if Disconnected() then
                     if not Reconnect(targetWorlds[twIndex]) then
                        stopScript("Gagal Menyambung ulang")
                        return false
                     end
                  end
                  
                  if getTile(matchTile[dx], y) and not getTile(matchTile[dx], y).readyharvest then
                     local delay = config.delay - timeout
                     harvested = true
                     
                     advSleep(delay > 0 and delay or 0, config.safeDelay)
                     break
                  end
                  
                  local px, py = getPos(); if not px then
                     stopScript("Gagal untuk menyambung ulang")
                     return false
                  end   
               
                  if math.abs(matchTile[dx] - px) >= 3 and math.abs(y - py) >= 3 then
                     if not Warp(targetWorlds[twIndex], true) then
                        stopScript("Gagal untuk warp ke Target World")
                        return false
                     end
                   
                     Notify("Mencoba kembali ke posisi target")
                  
                     if not Fp(matchTile[dx], y, true) then
                        stopScript("Gagal untuk findPath ke Target")
                        return false
                     end
                  end
                  timeout = 0
                  attempt = attempt + 1
               end 
            end
         end
      end
      
      if not collectHarvest() then
         return false
      end   
   end
   
   return true, x + 3 * stepX, isRetry, isRetryRow
end

